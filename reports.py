"""
reports.py - EXPORTS (CSV, JSON, printable summary)
====================================================
All exports are built from the same AdvisorOutput object, so they always match what the screen shows.
"""
from __future__ import annotations

import html
import json
from datetime import datetime

import pandas as pd

import explanation
from study_planner import minutes_text


def plan_dataframe(output) -> pd.DataFrame:
    """Today's study plan as a table (one row per subject)."""
    rec_by_name = {r.subject: r for r in output.recommendations}
    rows = []
    for a in output.allocations:
        rec = rec_by_name[a.name]
        rows.append({
            "Subject": a.name, "Priority": a.priority.capitalize(), "Urgency": rec.urgency.capitalize(),
            "Marks (%)": rec.marks, "Days left": rec.days_left, "Difficulty": rec.difficulty.capitalize(),
            "Weight": a.weight, "Share (%)": a.share_percent, "Study minutes per day": a.minutes,
            "Study time": minutes_text(a.minutes),
        })
    return pd.DataFrame(rows, columns=["Subject", "Priority", "Urgency", "Marks (%)", "Days left",
                                       "Difficulty", "Weight", "Share (%)", "Study minutes per day", "Study time"])


def timetable_dataframe(output) -> pd.DataFrame:
    rows = []
    for day in output.timetable:
        for a in day.allocations:
            rows.append({"Day": day.label, "Subject": a.name, "Priority": a.priority.capitalize(),
                         "Minutes": a.minutes, "Exam day": a.name in day.exam_subjects})
    return pd.DataFrame(rows, columns=["Day", "Subject", "Priority", "Minutes", "Exam day"])


def plan_to_csv(output) -> str:
    return plan_dataframe(output).to_csv(index=False)


def build_json_report(output) -> dict:
    s = output.summary
    return {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "note": "Advisory plan produced by a rule-based KRR system.",
        "student": {"name": output.student_name or None, "daily_study_hours": output.daily_hours},
        "inputs": [{"name": x.name, "marks": x.marks, "days_left": x.days_left,
                    "difficulty": x.difficulty, "confidence": x.confidence} for x in output.subjects],
        "knowledge_base": output.kb.to_dict(),
        "rules": [{"id": r.id, "name": r.name, "stage": r.stage, "if": r.if_text(output.kb),
                   "then": r.then_text(output.kb)} for r in output.rules],
        "reasoning": [dict(r.to_dict(), trace=explanation.trace_to_text(r)) for r in output.results],
        "plan": {
            "available_minutes": s.available_minutes, "allocated_minutes": s.allocated_minutes,
            "unallocated_minutes": s.unallocated_minutes, "block_minutes": s.block_minutes,
            "notes": s.notes,
            "subjects": [{"name": a.name, "priority": a.priority, "minutes": a.minutes,
                          "share_percent": a.share_percent} for a in output.allocations]},
        "timetable": [{"day": d.label, "exam_subjects": d.exam_subjects,
                       "allocations": [{"name": a.name, "minutes": a.minutes} for a in d.allocations]}
                      for d in output.timetable],
    }


def build_json_text(output) -> str:
    return json.dumps(build_json_report(output), indent=2, default=str)


def build_text_summary(output) -> str:
    who = output.student_name or "Student"
    s = output.summary
    lines = [f"SMART STUDY ADVISOR - STUDY SUMMARY for {who}",
             f"Daily study time: {minutes_text(s.available_minutes)}   |   Subjects: {len(output.subjects)}",
             "(Advisory plan generated by explicit IF-THEN rules)", "", "PRIORITIES AND DAILY PLAN"]
    for rec in output.recommendations:
        lines.append(f"- {rec.subject}: {rec.priority.upper()} priority, {rec.daily_time_text} per day "
                     f"(marks {rec.marks}%, exam in {rec.days_left} day(s), {rec.difficulty} difficulty)")
        if rec.urgency_warning:
            lines.append(f"    ! {rec.urgency_warning}")
        lines.append(f"    Why: {output.result_for(rec.subject).explanation}")
    lines += ["", f"Total allocated: {minutes_text(s.allocated_minutes)} of {minutes_text(s.available_minutes)}"]
    lines += [f"Note: {n}" for n in s.notes]
    return "\n".join(lines) + "\n"


def build_html_summary(output) -> str:
    """A clean one-page HTML file. Open it in a browser and press Ctrl+P to print or save as PDF."""
    esc = html.escape
    who = esc(output.student_name or "Student")
    s = output.summary
    rows = "".join(
        f"<tr><td>{esc(r.subject)}</td><td>{esc(r.priority.capitalize())}</td><td>{esc(r.daily_time_text)}</td>"
        f"<td>{r.marks}%</td><td>{r.days_left}</td><td>{esc(output.result_for(r.subject).explanation)}</td></tr>"
        for r in output.recommendations)
    notes = "".join(f"<li>{esc(n)}</li>" for n in s.notes)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Study summary</title>
<style>body{{font-family:Segoe UI,Arial,sans-serif;color:#1e1b4b;max-width:900px;margin:30px auto;padding:0 16px}}
h1{{color:#4338ca;margin-bottom:0}}table{{border-collapse:collapse;width:100%}}
th,td{{border:1px solid #c7d2fe;padding:8px;text-align:left;font-size:14px}}th{{background:#eef2ff}}
.muted{{color:#6b6b8d}}</style></head><body>
<h1>Smart Study Advisor</h1><p class="muted">Study summary for {who} - advisory plan from a rule-based KRR system</p>
<p>Daily study time: <b>{minutes_text(s.available_minutes)}</b> &middot; Allocated: <b>{minutes_text(s.allocated_minutes)}</b></p>
<table><tr><th>Subject</th><th>Priority</th><th>Daily time</th><th>Marks</th><th>Days left</th><th>Why</th></tr>{rows}</table>
<ul>{notes}</ul></body></html>"""
